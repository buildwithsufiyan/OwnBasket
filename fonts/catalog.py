def get_unique_pack_font_names():
    return get_unique_font_names_from_mapping(PACK_FONT_NAMES)


def get_unique_designer_font_names():
    return get_unique_font_names_from_mapping(DESIGNER_LIBRARY_FONT_NAMES)


def get_all_catalog_font_names():
    names = []
    seen = set()
    for mapping in (PACK_FONT_NAMES, DESIGNER_LIBRARY_FONT_NAMES):
        for font_name in get_unique_font_names_from_mapping(mapping):
            if font_name in seen:
                continue
            seen.add(font_name)
            names.append(font_name)
    return names


def get_unique_font_names_from_mapping(mapping):
    names = []
    seen = set()
    for item_fonts in mapping.values():
        for font_name in item_fonts:
            if font_name in seen:
                continue
            seen.add(font_name)
            names.append(font_name)
    return names


def build_reverse_font_mapping(mapping):
    reverse_mapping = {}
    for slug, font_names in mapping.items():
        for font_name in font_names:
            reverse_mapping.setdefault(font_name, []).append(slug)
    return reverse_mapping


DESIGNER_LIBRARY_SLUG_TO_NAME = {
    item['slug']: item['name']
    for item in DESIGNER_FONT_LIBRARIES
}
FONT_TO_DESIGNER_LIBRARY_SLUGS = build_reverse_font_mapping(DESIGNER_LIBRARY_FONT_NAMES)


def infer_font_category(font_name):
    if font_name in MONOSPACE_FONTS:
        return 'monospace'
    if font_name in SERIF_FONTS:
        return 'serif'
    if font_name in DISPLAY_FONTS:
        return 'display'
    if font_name in SCRIPT_FONTS:
        return 'script'
    if font_name in HANDWRITING_FONTS:
        return 'handwriting'
    return 'sans-serif'


def get_font_style_label(font_name, category=None):
    if font_name in STYLE_LABEL_OVERRIDES:
        return STYLE_LABEL_OVERRIDES[font_name]
    return DEFAULT_STYLE_LABELS.get(category or infer_font_category(font_name), 'Modern Sans Serif')


def get_designer_library_slugs_for_font(font_name):
    return FONT_TO_DESIGNER_LIBRARY_SLUGS.get(font_name, [])


def get_designer_library_names_for_font(font_name):
    return [
        DESIGNER_LIBRARY_SLUG_TO_NAME[slug]
        for slug in get_designer_library_slugs_for_font(font_name)
        if slug in DESIGNER_LIBRARY_SLUG_TO_NAME
    ]
